import { chromium } from "playwright";
const S = process.argv[2];
const API = "http://localhost:8003";
const stamp = Date.now().toString(36);
const email = `probe-${stamp}@example.com`;
const post = (p, b, t) => fetch(API + p, { method: "POST", headers: { "Content-Type": "application/json", ...(t ? { Authorization: `Bearer ${t}` } : {}) }, body: JSON.stringify(b) }).then((r) => r.json());
const tok = (await post("/auth/signup", { email, password: "correct horse", display_name: "Probe" })).access_token;
const ws = await post("/workspaces", { name: `Probe ${stamp}` }, tok);
const mtok = (await post("/auth/signup", { email: `m-${email}`, password: "correct horse", display_name: "Max" })).access_token;
await post("/workspaces/join-by-code", { code: ws.join_code }, mtok);
const b = await chromium.launch();
const page = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
page.on("console", (m) => m.type() === "error" && console.log("CONSOLE", m.text().slice(0, 200)));
await page.goto("http://localhost:8081", { waitUntil: "domcontentloaded", timeout: 240000 });
await page.getByRole("textbox").first().fill(email);
await page.locator("input[type=password]").first().fill("correct horse");
await page.getByRole("button", { name: /^(sign in|sign in with email|continue with email)$/i }).first().click();
await page.getByText("No meetings yet").first().waitFor({ timeout: 120000 });
await page.getByRole("button", { name: "New meeting" }).first().click();
const t = async (n, f) => { try { await f(); console.log("ok", n); } catch (e) { console.log("FAIL", n, e.message.split(String.fromCharCode(10)).slice(0, 6).join(" | ")); await page.screenshot({ path: `${S}/probe_${n}.png` }); } };
await t("title", () => page.getByRole("textbox").first().fill("Weekly sync", { timeout: 8000 }));
await t("max", () => page.getByText("Max", { exact: true }).first().click({ timeout: 8000 }));
await t("guest", () => page.getByRole("textbox").nth(1).fill("Imran", { timeout: 8000 }));
await t("add", () => page.getByRole("button", { name: "Add", exact: true }).click({ timeout: 8000 }));
await t("create", () => page.getByRole("button", { name: "Create meeting" }).click({ timeout: 8000 }));
await t("waiting", () => page.getByText("Waiting for audio").first().waitFor({ timeout: 15000 }));
await page.screenshot({ path: `${S}/probe.png` });
await b.close();
