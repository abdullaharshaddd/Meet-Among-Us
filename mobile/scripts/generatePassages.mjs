// Generates src/lib/enrollmentPassages.gen.ts from the backend's single copy of the
// enrollment passages. Run it after editing backend/app/content/enrollment_passages.json:
//   npm run generate:passages
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "..", "..", "backend", "app", "content", "enrollment_passages.json");
const target = join(here, "..", "src", "lib", "enrollmentPassages.gen.ts");

const content = JSON.parse(readFileSync(source, "utf-8"));
const passages = content.passages.map((passage) => ({
  language: passage.language,
  title: passage.title,
  text: passage.text,
  isUrdu: passage.is_urdu,
}));

const file = `// GENERATED by scripts/generatePassages.mjs from backend/app/content/enrollment_passages.json.
// Do not edit by hand; edit the JSON and run \`npm run generate:passages\`.

export const minSpeechSeconds = ${content.min_speech_seconds};

export const generatedPassages: {
  language: "en" | "ur" | "mixed";
  title: string;
  text: string;
  isUrdu: boolean;
}[] = ${JSON.stringify(passages, null, 2)};
`;

writeFileSync(target, file, "utf-8");
console.log(`wrote ${target}`);
